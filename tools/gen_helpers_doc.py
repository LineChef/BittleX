#!/usr/bin/env python3
"""Generate docs/guides/shell-helpers.md -- a reference of every `g2*` shell helper -- from the comments in tools/g2_aliases.sh. Stdlib only.

    python tools/gen_helpers_doc.py           # rewrite docs/guides/shell-helpers.md
    python tools/gen_helpers_doc.py --check   # exit 1 if the page is out of date (the doc checker runs this)

Single source of truth: the helper definitions and their comments in tools/g2_aliases.sh. A helper's description is, in order, the
usage comment `# g2name <args>  -- what it does` (with its indented continuation lines), else the comment trailing its definition line.
Section headings come from the `# ---- title ----` rules in that file.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(HERE, "g2_aliases.sh")
OUT = os.path.join(ROOT, "docs", "guides", "shell-helpers.md")

DEF = re.compile(r"^(g2[a-z0-9-]*)\(\)\s*\{(.*)$")
SECTION = re.compile(r"^# -{5,}\s*(.*?)\s*-*\s*$")


def parse(lines):
    usage = {}  # name -> (usage text, description)
    for i, line in enumerate(lines):
        m = re.match(r"^#\s+(g2[a-z0-9-]*)\b(.*)$", line)
        if not m or " -- " not in m.group(2):
            continue
        name = m.group(1)
        if name in usage:
            continue
        head, _, rest = m.group(2).partition(" -- ")
        text = [rest.strip()]
        j = i + 1
        while j < len(lines) and re.match(r"^#\s{2,}\S", lines[j]) and not re.match(r"^#\s+g2[a-z0-9-]*\b.* -- ", lines[j]):
            text.append(lines[j][1:].strip())
            j += 1
        usage[name] = ((name + " " + head.strip()).strip(), " ".join(t for t in text if t))
    sections, current, seen = [], "General", set()
    for line in lines:
        s = SECTION.match(line)
        if s and s.group(1):
            current = s.group(1).strip("- ").strip()
            continue
        d = DEF.match(line)
        if not d or d.group(1) in seen:
            continue
        name, rest = d.group(1), d.group(2)
        seen.add(name)
        t = re.search(r"[{}]\s*;?\s+#\s+(.*)$", rest)
        trailing = t.group(1).strip() if t else (rest.strip()[1:].strip() if rest.strip().startswith("#") else "")
        use, desc = usage.get(name, (name, trailing))
        if not desc:
            desc = trailing
        if not sections or sections[-1][0] != current:
            sections.append((current, []))
        sections[-1][1].append((use, desc))
    return sections


def build():
    lines = open(SRC, encoding="utf-8").read().splitlines()
    out = ["# Shell helpers (`g2*`)", "",
           "> **Generated** by `tools/gen_helpers_doc.py` from the comments in [`tools/g2_aliases.sh`](../../tools/g2_aliases.sh). Do not edit this file: change the",
           "> comment next to the helper, then re-run the script (the pre-commit doc check tells you when it is stale).", "",
           "Load the helpers once with `source tools/g2_aliases.sh` (add that line to `~/.zshrc`). Every helper except `g2` and `g2rl` runs in a subshell, so it works",
           "from any directory and leaves you where you were. `g2help` prints the bare list. Commands in task order: [`cheatsheet.md`](cheatsheet.md).", ""]
    for title, rows in parse(lines):
        out += [f"## {title}", "", "| Command | What it does |", "|---|---|"]
        for use, desc in rows:
            desc = re.sub(r"\s+", " ", desc).strip()[:420] or "—"
            out.append(f"| `{use.replace('|', '/')}` | {desc.replace('|', '/')} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("docs/guides/shell-helpers.md is out of date: run python tools/gen_helpers_doc.py")
            return 1
        return 0
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
