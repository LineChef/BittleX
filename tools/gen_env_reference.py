#!/usr/bin/env python3
"""Generate docs/guides/env-reference.md -- every `G2_*` environment variable the code reads -- from the source. Stdlib only.

    python tools/gen_env_reference.py           # rewrite docs/guides/env-reference.md
    python tools/gen_env_reference.py --check   # exit 1 if the page is out of date (the doc checker runs this)

For each variable: its default where the code states one in the read (`_env("G2_X", "1")`, `os.environ.get("G2_X", ...)`), the files that read it, and the
docs that mention it. Variables no doc mentions are listed first, so a new switch cannot go undocumented unnoticed. The curated guide to the switches people
change most is `settings-switches.md`.
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "docs", "guides", "env-reference.md")
READ = re.compile(r"(?:_env\w*|environ\.get|environ\[|getenv)\(?\s*[\"'](G2_[A-Z0-9_]+)[\"']\s*(?:,\s*([^\n)]*))?")
MENTION = re.compile(r"(?<![A-Za-z0-9_])G2_[A-Z0-9_]+")


def git(*a):
    for exe in ("git", "/Library/Developer/CommandLineTools/usr/bin/git"):
        try:
            r = subprocess.run([exe, *a], cwd=ROOT, capture_output=True, text=True)
        except OSError:
            continue
        if r.returncode == 0:
            return r.stdout
    return ""


def collect():
    files = git("ls-files").split()
    reads, mentions_code = {}, {}
    for f in files:
        if not f.endswith((".py", ".sh")) or "/tests/" in f or not f.startswith(("pi_pipeline/", "tools/")) or f == "tools/gen_env_reference.py":
            continue
        s = open(os.path.join(ROOT, f), encoding="utf-8").read()
        for m in READ.finditer(s):
            d = (m.group(2) or "").strip().rstrip(",").strip()
            reads.setdefault(m.group(1), {"default": d, "files": set()})["files"].add(f)
        for v in set(MENTION.findall(s)):
            mentions_code.setdefault(v, set()).add(f)
    docs = {}
    for f in files:
        if (f.endswith(".md") and f.startswith("docs/") and not f.startswith("docs/archive/") and f != "docs/guides/env-reference.md"
                and not f.startswith("docs/rl/results-index")) or f == ".env.example":
            for v in set(MENTION.findall(open(os.path.join(ROOT, f), encoding="utf-8").read())):
                docs.setdefault(v, set()).add(f)
    return reads, mentions_code, docs


def build():
    reads, mentions, docs = collect()
    names = sorted(v for v in set(reads) | set(mentions) if not v.endswith("_"))
    undocumented = [v for v in names if v not in docs]

    def where(v):
        fs = sorted((reads.get(v, {}).get("files") or mentions.get(v) or []))
        return ", ".join(f"`{os.path.basename(f)}`" for f in fs[:3]) + (f" +{len(fs) - 3}" if len(fs) > 3 else "")

    def doclinks(v):
        ds = sorted(docs.get(v, []))
        return ", ".join(f"[`{os.path.basename(d)}`]({os.path.relpath(d, 'docs/guides')})" for d in ds[:3]) + (f" +{len(ds) - 3}" if len(ds) > 3 else "") or "not documented"

    def row(v):
        d = reads.get(v, {}).get("default", "")
        d = f"`{d[:40]}`" if d else "—"
        return f"| `{v}` | {d.replace('|', '/')} | {where(v)} | {doclinks(v)} |"

    out = ["# Environment variables (`G2_*`)", "",
           "> **Generated** by `tools/gen_env_reference.py` from the source. Do not edit this file: the pre-commit doc check tells you when it is stale.", "",
           f"Every `G2_*` variable the Pi code and the tools read: **{len(names)}**, of which **{len(undocumented)}** are not yet described in any guide. Set them in the repo-root `.env` "
           "(on the Pi, the Pi's own `.env`). The defaults shown are the fallback written at the point of the read, which can be a name or an expression; the curated guide to the "
           "switches people change most is [`settings-switches.md`](settings-switches.md). Feature flags: [`feature-flags.md`](feature-flags.md).", ""]
    if undocumented:
        out += ["## Not described in any guide yet", "", "Add a line for each to `settings-switches.md` (or the guide for its subsystem), then regenerate this page.", "",
                "| Variable | Default at the read | Read in | Documented in |", "|---|---|---|---|"] + [row(v) for v in undocumented] + [""]
    out += ["## All variables", "", "| Variable | Default at the read | Read in | Documented in |", "|---|---|---|---|"] + [row(v) for v in names] + [""]
    return "\n".join(out).rstrip() + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("docs/guides/env-reference.md is out of date: run python tools/gen_env_reference.py")
            return 1
        return 0
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
