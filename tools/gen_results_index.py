#!/usr/bin/env python3
"""Generate docs/rl/results-index.md -- an index of the tracked result files under rl_training/opencat-gym/trained/ -- from git. Stdlib only.

    python tools/gen_results_index.py           # rewrite docs/rl/results-index.md
    python tools/gen_results_index.py --check   # exit 1 if the page is out of date (the doc checker runs this)

The checkpoints, logs and run folders in trained/ are gitignored; the small result files that back decisions (benchmark JSON, exported release
policies, reports) are force-added. For each tracked file this lists its size and the docs that cite it by name, so a result can be traced to the
decision it backs. Files no doc cites are listed as such (they are still the raw evidence).
"""
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "docs", "rl", "results-index.md")
TRAINED = "rl_training/opencat-gym/trained/"


def git(*a):
    """Run git. Under an x86_64 (Rosetta) interpreter the /usr/bin/git shim cannot start (xcrun has no x86_64 slice), so fall back to the real binary."""
    for exe in ("git", "/Library/Developer/CommandLineTools/usr/bin/git"):
        try:
            r = subprocess.run([exe, *a], cwd=ROOT, capture_output=True, text=True)
        except OSError:
            continue
        if r.returncode == 0:
            return r.stdout
    return ""


def family(name):
    base = re.sub(r"\.(onnx\.json|onnx|json|log|txt|md)$", "", name)
    m = re.match(r"(Release_Candidate|V\dcand|decathlon|gaits|phase\d?[A-Za-z]*|abD|e\d[a-z]?|eskill|hw\d|mce|v\d+|final|hs|sweep|base)", base)
    return m.group(1) if m else base.split("_")[0]


def build():
    files = [f for f in git("ls-files", TRAINED).splitlines() if f]
    docs = [f for f in git("ls-files", "docs").splitlines() if f.endswith(".md") and f != "docs/rl/results-index.md"]
    text = {}
    for d in docs:
        try:
            text[d] = open(os.path.join(ROOT, d), encoding="utf-8").read()
        except OSError:
            pass
    rows = {}
    for f in files:
        name = f[len(TRAINED):]
        base = name.split("/")[-1]
        cites = sorted(d for d, t in text.items() if base in t or name in t)
        size = os.path.getsize(os.path.join(ROOT, f)) if os.path.exists(os.path.join(ROOT, f)) else 0
        rows.setdefault(family(base), []).append((name, size, cites))
    out = ["# Results index", "",
           "> **Generated** by `tools/gen_results_index.py` from git. Do not edit this file: re-run the script (the pre-commit doc check tells you when it is stale).", "",
           "The small result files that back decisions are tracked under `rl_training/opencat-gym/trained/` (the checkpoints, logs and run folders beside them are not). "
           "This lists each tracked file with its size and the docs that cite it by name. The pipeline that produces them: [`training-pipeline.md`](training-pipeline.md).", ""]
    total = 0
    generic = {"base", "final", "sweep", "hs", "v4", "v5", "v6", "v3", "hw1", "e3", "e4c", "e5"}
    for fam in sorted(rows, key=lambda x: (x.lower())):
        out += [f"## `{fam}`", ""]
        if fam not in generic and len(fam) >= 3:
            rx = re.compile(r"(?<![A-Za-z0-9])" + re.escape(fam) + r"(?![A-Za-z0-9])")
            hits = sorted(d for d, t in text.items() if rx.search(t))
            if hits:
                out += ["Docs that mention this family: " + ", ".join(f"[`{os.path.basename(c)}`]({os.path.relpath(c, 'docs/rl')})" for c in hits[:4]) + (f" +{len(hits) - 4}" if len(hits) > 4 else "") + ".", ""]
        out += ["| File | Size | Cited by |", "|---|---|---|"]
        for name, size, cites in sorted(rows[fam]):
            total += size
            links = ", ".join(f"[`{os.path.basename(c)}`]({os.path.relpath(c, 'docs/rl')})" for c in cites[:4]) or "not cited"
            if len(cites) > 4:
                links += f" +{len(cites) - 4}"
            out.append(f"| `{name}` | {size/1024:.0f} KB | {links} |")
        out.append("")
    out.insert(5, f"**{sum(len(v) for v in rows.values())} files, {total/1e6:.1f} MB.**\n")
    return "\n".join(out).rstrip() + "\n"


def main():
    text = build()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if cur != text:
            print("docs/rl/results-index.md is out of date: run python tools/gen_results_index.py")
            return 1
        return 0
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
